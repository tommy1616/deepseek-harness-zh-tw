const TAIWAN_PHRASE_MAP = new Map(TAIWAN_PHRASES)
const TAIWAN_PHRASE_PATTERN = new RegExp(
  TAIWAN_PHRASES.map(([from]) => from.replace(/[.*+?^${}()|[\]\\]/gu, '\\$&')).join('|'),
  'gu',
)

const PHRASE_ENTRIES = Object.entries(PHRASES)

/** Convert one translated template to Taiwan Traditional Chinese. */
export function toTaiwanChinese(value: string): string {
  let result = PHRASES[value] ?? value
  if (result === value) {
    for (const [from, to] of PHRASE_ENTRIES) result = result.replaceAll(from, to)
    result = result.replace(/[\u3400-\u9fff]/gu, character => CHARACTERS[character] ?? character)
  }
  return result.replace(TAIWAN_PHRASE_PATTERN, match => TAIWAN_PHRASE_MAP.get(match) ?? match)
}

/** Derive a detached zh-TW dictionary from a Simplified Chinese dictionary. */
export function toTaiwanChineseDictionary(dict: Readonly<Record<string, string>>): Record<string, string> {
  return Object.fromEntries(Object.entries(dict).map(([key, value]) => [key, toTaiwanChinese(value)]))
}
